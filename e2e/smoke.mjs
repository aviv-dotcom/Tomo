// Smoke test of stage 1 on a live site: sign in, set up a business, add people, sign out.
// Usage: node e2e/smoke.mjs <env file with Supabase URL, anon and service role keys> [screenshot dir]
// Creates a test user and business; delete them afterwards (see the ids file it writes).
import { createRequire } from "node:module";
import fs from "node:fs";
const require = createRequire(import.meta.url);
const { createServerClient } = require("@supabase/ssr");
const { chromium } = require("playwright");
const env = Object.fromEntries(fs.readFileSync(process.argv[2], "utf8").split("\n").filter(l => l.includes("=")).map(l => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]));
const URL_ = env.NEXT_PUBLIC_SUPABASE_URL, ANON = env.NEXT_PUBLIC_SUPABASE_ANON_KEY, SR = env.SUPABASE_SERVICE_ROLE_KEY;
const SITE = process.env.SITE ?? "https://tomo-iota.vercel.app", OUT = process.argv[3] ?? ".";
const email = `e2e-${Date.now()}@example.com`;
const admin = (p, body) => fetch(`${URL_}/auth/v1/admin/${p}`, { method: "POST", headers: { apikey: SR, Authorization: `Bearer ${SR}`, "Content-Type": "application/json" }, body: JSON.stringify(body) }).then(r => r.json());
const user = await admin("users", { email, email_confirm: true });
const link = await admin("generate_link", { type: "magiclink", email });
const otp = link.email_otp ?? link.properties?.email_otp;
let jar = [];
const sb = createServerClient(URL_, ANON, { cookies: { getAll: () => jar, setAll: (list) => { for (const c of list) { jar = jar.filter(x => x.name !== c.name); if (c.value) jar.push({ name: c.name, value: c.value }); } } } });
const { error } = await sb.auth.verifyOtp({ email, token: otp, type: "email" });
if (error) throw new Error("verifyOtp: " + error.message);
console.log("user", user.id, "cookies", jar.map(c => c.name).join(","));
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: "he-IL" });
await ctx.addCookies(jar.map(c => ({ name: c.name, value: c.value, domain: new URL(SITE).hostname, path: "/", secure: true, sameSite: "Lax" })));
const page = await ctx.newPage();
const errors = []; page.on("pageerror", e => errors.push(e.message));
await page.goto(SITE + "/"); await page.waitForURL("**/start");
console.log("1 redirected to", new URL(page.url()).pathname);
await page.fill('input[name="name"]', "Liron Beauty Test");
await page.click('label.tile:has-text("יופי וטיפוח")');
const slug = await page.inputValue('input[name="slug"]');
await page.screenshot({ path: `${OUT}/e2e-1-start.png`, fullPage: true });
await page.click('button:has-text("להקים את העסק")');
await page.waitForURL(`**/b/${slug}`, { timeout: 30000 });
console.log("2 business created at", new URL(page.url()).pathname);
await page.screenshot({ path: `${OUT}/e2e-2-today.png`, fullPage: true });
await page.fill('input[name="name"]', "נועה שגיא");
await page.fill('input[name="phone"]', "052-1234567");
await page.click('button:has-text("להוסיף")');
await page.waitForSelector('.list-row:has-text("נועה שגיא")', { timeout: 20000 });
await page.fill('input[name="name"]', "שירה אביב");
await page.check('input[name="lead"]');
await page.click('button:has-text("להוסיף")');
await page.waitForSelector('.list-row:has-text("שירה אביב")', { timeout: 20000 });
const kpis = await page.$$eval(".kpi b", els => els.map(e => e.textContent));
console.log("3 people added, kpis", kpis.join(" / "));
await page.screenshot({ path: `${OUT}/e2e-3-people.png`, fullPage: true });
await page.goto(SITE + "/"); await page.waitForURL(`**/b/${slug}`);
console.log("4 returning user goes straight to", new URL(page.url()).pathname);
await page.click('button:has-text("יציאה")'); await page.waitForURL(SITE + "/");
await page.goto(SITE + `/b/${slug}`); await page.waitForURL("**/login");
console.log("5 after sign-out the business page asks to log in");
console.log("page errors:", errors.length ? errors : "none");
fs.writeFileSync(`${OUT}/e2e-ids.json`, JSON.stringify({ user: user.id, email, slug }));
await browser.close();
