// Smoke test of the money screens on a live site: a pay-per-visit appointment is marked attended, the client owes the
// price, a partial payment is recorded, a manual charge is added, and the money screen shows the debt.
// Usage: node e2e/money.mjs <env file with Supabase URL, anon and service role keys> [screenshot dir]
// Creates a test user and business; delete them afterwards (see the ids file it writes).
import { createRequire } from "node:module";
import fs from "node:fs";
const require = createRequire(import.meta.url);
const { createServerClient } = require("@supabase/ssr");
const { chromium } = require("playwright");
const env = Object.fromEntries(fs.readFileSync(process.argv[2], "utf8").split("\n").filter((l) => l.includes("=")).map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]));
const URL_ = env.NEXT_PUBLIC_SUPABASE_URL, ANON = env.NEXT_PUBLIC_SUPABASE_ANON_KEY, SR = env.SUPABASE_SERVICE_ROLE_KEY;
const SITE = process.env.SITE ?? "https://tomo-iota.vercel.app", OUT = process.argv[3] ?? ".";
const email = `e2e-money-${Date.now()}@example.com`;
const admin = (p, body) => fetch(`${URL_}/auth/v1/admin/${p}`, { method: "POST", headers: { apikey: SR, Authorization: `Bearer ${SR}`, "Content-Type": "application/json" }, body: JSON.stringify(body) }).then((r) => r.json());
const user = await admin("users", { email, email_confirm: true });
const link = await admin("generate_link", { type: "magiclink", email });
let jar = [];
const sb = createServerClient(URL_, ANON, { cookies: { getAll: () => jar, setAll: (list) => { for (const c of list) { jar = jar.filter((x) => x.name !== c.name); if (c.value) jar.push({ name: c.name, value: c.value }); } } } });
const { error } = await sb.auth.verifyOtp({ email, token: link.email_otp ?? link.properties?.email_otp, type: "email" });
if (error) throw new Error("verifyOtp: " + error.message);
fs.writeFileSync(`${OUT}/e2e-money-ids.json`, JSON.stringify({ user: user.id, email }));
const step = (n, msg) => console.log(`${n} ${msg}`);
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: "he-IL", timezoneId: "Asia/Jerusalem" });
await ctx.addCookies(jar.map((c) => ({ name: c.name, value: c.value, domain: new URL(SITE).hostname, path: "/", secure: true, sameSite: "Lax" })));
const page = await ctx.newPage();
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
await page.goto(SITE + "/"); await page.waitForURL("**/start");
await page.fill('input[name="name"]', `Money Studio ${Date.now() % 100000}`);
await page.click('label.tile:has-text("יופי וטיפוח")');
const slug = await page.inputValue('input[name="slug"]');
await page.click('button:has-text("להקים את העסק")'); await page.waitForURL(`**/b/${slug}`);
fs.writeFileSync(`${OUT}/e2e-money-ids.json`, JSON.stringify({ user: user.id, email, slug }));
await page.fill('input[name="name"]', "נועה שגיא"); await page.fill('input[name="phone"]', "052-1234567");
await page.click('button:has-text("להוסיף")'); await page.waitForSelector('.list-row:has-text("נועה שגיא")');
await page.goto(`${SITE}/b/${slug}/calendar/hours`);
for (let d = 0; d < 7; d++) { await page.check(`input[name="open-${d}"]`); await page.fill(`input[name="start-${d}"]`, "09:00"); await page.fill(`input[name="end-${d}"]`, "20:00"); }
await page.click('button:has-text("לשמור שעות")'); await page.waitForSelector("text=השעות נשמרו");
const tomorrow = new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Jerusalem" }).format(new Date(Date.now() + 864e5));
await page.goto(`${SITE}/b/${slug}/calendar/new?d=${tomorrow}`);
await page.selectOption('select[name="person"]', { label: "נועה שגיא" });
await page.waitForSelector(".slot"); await page.click(".slot:nth-child(2)");
await page.click('button:has-text("לקבוע")'); await page.waitForURL(`**/calendar?d=${tomorrow}`);
await page.click(".session"); await page.waitForURL("**/calendar/s/**");
await page.click('.list-row:has-text("נועה שגיא") button:has-text("הגיע")');
await page.waitForSelector('.list-row:has-text("לבטל סימון")');
step(1, `business ${slug}: appointment marked attended`);
await page.click('a:has-text("נועה שגיא")'); await page.waitForURL("**/people/**");
step(2, "balance after visit: " + (await page.textContent("#money .card-title .tag")));
await page.fill('#money input[name="amount"]', "200");
await page.selectOption('#money select[name="method"]', "bit");
await page.click('#money button:has-text("לרשום")');
await page.waitForFunction(() => document.querySelector("#money .card-title .tag")?.textContent?.includes("180"));
step(3, "after paying 200 by Bit: " + (await page.textContent("#money .card-title .tag")));
await page.fill('#money input[name="description"]', "מוצר: קרם הרגעה");
await page.fill('#money form:has(input[name="description"]) input[name="amount"]', "140");
await page.click('#money button:has-text("להוסיף חיוב")');
await page.waitForFunction(() => document.querySelector("#money .card-title .tag")?.textContent?.includes("320"));
step(4, "after a 140 product charge: " + (await page.textContent("#money .card-title .tag")));
await page.screenshot({ path: `${OUT}/e2e-money-1-card.png`, fullPage: true });
await page.goto(`${SITE}/b/${slug}/money`);
const kpis = await page.$$eval(".kpi b", (e) => e.map((x) => x.textContent));
const debtors = await page.$$eval(".card:has(h2:has-text('מי חייב')) .list-row .grow", (e) => e.map((x) => x.innerText.replace(/\s+/g, " ")));
step(5, `money screen: collected ${kpis[0]}, open ${kpis[1]}, owes: ${debtors.join(" | ")}`);
await page.screenshot({ path: `${OUT}/e2e-money-2-screen.png`, fullPage: true });
await page.goto(`${SITE}/b/${slug}`);
step(6, "Today collected: " + (await page.textContent('.kpi:has-text("נגבה החודש") b')));
console.log("page errors:", errors.length ? errors : "none");
await browser.close();
